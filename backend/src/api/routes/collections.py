def optimize_cover_url(url: str | None, width: int = 260) -> str | None:
    """Normalize and optimize cover URLs across Google, Comic Vine, IA, and Open Library."""
    if not url or not isinstance(url, str):
        return None

    url = url.strip()
    if not url:
        return None

    # 1. Unwrap pre-existing wsrv.nl proxy wrappers to avoid double proxying
    if "wsrv.nl/?url=" in url or "wsrv.nl?" in url:
        parts = url.split("url=")
        if len(parts) > 1:
            url = unquote(parts[-1].split("&")[0])

    # 2. Force HTTPS
    if url.startswith("http://"):
        url = "https://" + url[7:]

    # 3. GOOGLE BOOKS: Direct fetch (Google blocks proxy scrapers with 403)
    if "books.google.com" in url or "googleusercontent.com" in url:
        if "edge=curl" in url:
            url = url.replace("edge=curl", "")
        return url

    # 4. COMIC VINE: Direct fetch (Comic Vine WAF blocks wsrv.nl proxy with 403 Forbidden)
    if "comicvine.gamespot.com" in url or "static.comicvine.com" in url or "cbsistatic.com" in url:
        return url

    # 5. INTERNET ARCHIVE, OPEN LIBRARY, & OTHERS:
    # Route through Cloudflare Edge CDN (wsrv.nl) -> converts heavy PNG/JPG into ~15KB WebP
    encoded_target = quote(url, safe="")
    return f"https://wsrv.nl/?url={encoded_target}&w={width}&output=webp"


def _card_summary(item: dict[str, Any]) -> dict[str, Any]:
    """Extract lightweight card fields for Home feed (reduces JSON payload size by 90%)."""
    raw_cover = item.get("cover_url", "") or ""
    optimized_cover = optimize_cover_url(raw_cover, width=300)

    author = item.get("author")
    authors = item.get("authors", [])
    if not author and authors:
        author = authors[0] if isinstance(authors, list) else str(authors)

    cid = item.get("content_id") or item.get("id") or ""

    return {
        "content_id": str(cid),
        "id": str(cid),
        "title": item.get("title", "Unknown"),
        "author": author or "Unknown Author",
        "cover_url": optimized_cover,
        "content_type": item.get("content_type", "book"),
        "is_free": bool(item.get("is_free", False)),
        "free_url": item.get("free_url"),
        "source": item.get("source", "google_books"),
        "genres": item.get("genres", []),
    }
