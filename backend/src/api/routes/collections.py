def _ratings_fingerprint(user_ratings: list[dict[str, Any]]) -> str:
    if not user_ratings:
        return "no-ratings"
    parts = sorted(
        f"{r.get('content_id', '')}:{r.get('rating', '')}"
        for r in user_ratings
    )
    return hashlib.md5("|".join(parts).encode("utf-8")).hexdigest()[:10]


async def _get_optional_user(
    credentials: HTTPAuthorizationCredentials | None = Depends(_bearer),
    db: AsyncSession = Depends(get_db),
) -> User | None:
    if credentials is None:
        return None

    user_id_str = verify_token(credentials.credentials, expected_type="access")
    if user_id_str is None:
        return None

    try:
        from uuid import UUID
        user_id = UUID(user_id_str)
    except ValueError:
        return None

    return await get_by_id(db, user_id)


